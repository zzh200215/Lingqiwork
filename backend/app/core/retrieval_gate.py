"""确定性检索质量门 + 重搜策略 —— P2 的**纯函数层**（与编排图解耦）。

方案 §2 P2 的三个克制之二原话：「质量门是确定性函数，不是模型判断：候选分数分布……
**绝不让模型判断『检索得好不好』**（它判断不了，还慢）」。纪律之三：「质量门与策略池是
纯函数、与图解耦（图只管编排）——万一要退，编排层换回自研 if/重试，纯函数一行不动」。
所以这一层不认识 LangGraph、也不认识 chat：**给它一组命中，它说够不够；给它用过的策略，
它说下一步换哪个**。

**判据是量出来的，不是拍的**（`RAG升级.md` §3「P2 前置 · 质量门可分性」）。**2026-09-23 重量过
一次，样本从 44 条扩到 63 条**（补了失败正样本：`bad` 从 4 → 10，见下面那张新表）——
这一次的读数和上一次**不一样，而且是往差的方向走**：

| 信号 | 门口径 AUC（旧 44 条） | 门口径 AUC（新 63 条） |
|---|---|---|
| `vec_top1`（向量路原始相似度） | 0.800 | **0.696** |
| `both_frac`（top-k 里双通道占比） | 0.787 | **0.712**（现在是两者里更强的那个） |
| `top1`（RRF 分） | 0.733 | 0.675 |
| `top1−top3 分差` | 0.154 | 0.245（**方向仍然是反的**） |
| `命中通道数` / `返回条数` | 0.500 | 0.500（仍然没有方差） |

**为什么掉了**：新补的 6 条失败样本几乎都是**「差一口气」的形状**——检索回来了一个**相近**
的东西（压缩章输给第一性原理章、SOP 速查卡输给它的父章节、一条完全无关的模板文件排第一）。
这些情况下**向量相似度照样很高**，门于是说「够」。也就是说：**这个门分得开「答非所问」，
分不开「找到了相近的一份」**——而后者恰恰是个人库里最常见的失败。

**规则扫描（新样本，误放率 ≤ 上限时好检索的放行率）**：

    误放 ≤ 5%  → 放行 41%（`vec ≥ 0.6644`）
    误放 ≤ 10% → 放行 49%（`vec ≥ 0.6339 且 both_frac ≥ 0.6`）
    误放 ≤ 15% → 放行 54%（`vec ≥ 0.6339`）
    误放 ≤ 20% → 放行 56%（`vec ≥ 0.6226`）

**上线那个运行点在新样本上的实测**（`smoke_quality_gate.py` 末尾自检）：**好检索放行 56%、
误放 21%**——与上面 `vec ≥ 0.6134 且 both_frac ≥ 0.6` 那一行一致。**旧 docstring 里写的
「放行 63% / 误放 7%」是小样本（4 条失败正样本，全在 paraphrase）撑出来的，别再用那个数。**

**这里是刻意的：阈值没有跟着改**（`VEC_FLOOR` / `BOTH_FLOOR` 一个字节没动）。理由有三：
① 改运行点是一次**产品决定**，读数先摆出来；② 门的**用途在 P2 落地时已经变了**——它不再触发
重搜，而是只在 chat 注入里加一句「材料里没有直接相关的」并禁止硬答。用途一变，**代价不对称
也跟着变**：今天更贵的是**误报**（对一次好检索说「没有」），而不是误放——所以"按 10% 误放去
重调"这个目标本身要先想清楚是不是现在的目标；③ **2026-09-24 量出来：在这 63 条上换点，
换到的是噪声**（见下一节）。

**2026-09-24 追加：上面那张扫描表不能当可达目标读**（`smoke_quality_gate.py` 现在自带交叉验证）。
规则族是几百条，在**同一批 63 条**上取最大，白捡几个点是必然的。把同一族放进
**5 折 × 20 次重复**（只在训练折上挑、在留出折上算）之后：

| 误放率上限 | 样本内（扫描表） | 留出（诚实） |
|---|---|---|
| ≤ 10% | 放行 49% / 误放 8% | **放行 39% / 误放 26%** |
| ≤ 15% | 放行 54% / 误放 12% | 放行 48% / 误放 28% |
| ≤ 20% | 放行 56% / 误放 17% | 放行 55% / 误放 29% |

**没有一档在留出上同时赢过现在这个运行点**（放行 56% / 误放 21%）——扫描表里的「误放 ≤ 10%」
出了样本就变成 26%，越调越差。所以结论不是「换个更好的点」，是**这 63 条不够**：
硬负样本只有 10 条，`bad` 那一桶的 AUC 也只有 0.594（`both_frac`，见下）。
**要动运行点，先扩样本。**

**门分不开的是哪一种失败——两列 AUC 摆着**（`smoke_quality_gate.py` 的表里分桶印）：
`both_frac` 对「库里根本没有」（`no_answer` 那 14 条）是 **0.797**，对「找到了相近的一份」
（`bad` 那 10 条）只有 **0.594**；`vec_top1` 是 0.722 / 0.659。也就是说：
**「有没有材料」认得出，「材料对不对」认不出。** 这不是本项目实现得差——CRAG 论文
（arXiv 2401.15884 §4.2）为这一步专门**微调了一个 0.77B 的评估器**，而且它的负样本正是
「检索回来、与问题很像但不相关」的那些（与本项目新补的 6 条同形）；即便那样，§4.3 还要再加一个
`AMBIGUOUS` 中间档，并明说「只用 Correct / Incorrect 两档时，效果很容易被评估器的精度拖累」。
所以本项目的取舍（§2 P2 克制之二「绝不让模型判断检索好不好」）站得住：
**那条路要的不是一句提示词，是训练。**

**今天谁在用这一层（2026-09-24 复核）**：运行时只有一个调用方——`routers/chat.py` 的
`rag_gate = retrieval_gate.assess(sources)`，判定只改**注入的那段话**（`_build_rag_context`
在门不过时加一段「这批片段里没有与当前问题直接相关的材料」，片段照旧全给它）。
**重搜那半截（`next_strategy` / `should_retry` / `RETRY_ORDER` / `MAX_RETRIES`）今天没有调用方**：
CRAG 试点结论是净负、LangGraph 整体撤出运行时（`Agent升级.md` §4.1），编排层已经没有那一步。
留着是刻意的（纯函数层是「万一要退」的退路，单测钉着它），但读的人要知道两件事：
① 它在那儿**不代表今天会重搜**；② 「误放 = 该重搜却直接答」这个代价口径**已经过期**——
今天的代价是那段话。

**判据的定义只能有一处（踩过一次）**：`vec_top1` / `both_frac` 的量法与线上必须调**同一个
函数、同一份命中**。第一版量法自己用 `indexer.search(query, k)[0]["score"]` 取向量通道的
top1，而线上经过 RRF 融合与 `_diversify` 限块，两边差到 **0.0635**——阈值直接失效。
所以 `smoke_quality_gate.py` 现在调的就是本模块的函数，它末尾还会把 `assess` 原样跑一遍
自检运行点。

**两条已知边界，别把它当万能的**：
1. 这个门分不开「答案不在库里」与「答案在库里但没检索到」——前者重搜是白搜。它只回答
   「这一把材料够不够好」，回答不了「该不该重搜」（后半句是策略池的事）。
2. **阈值是在当时的样本上定的，样本一换就该重量**（`smoke_quality_gate.py` 免费可复跑）——
   2026-09-23 那次扩容就是活例子：样本从 44 → 63，AUC 与运行点都变了。
"""
from dataclasses import dataclass

# 运行点：`VEC_FLOOR` / `BOTH_FLOOR` 是**44 条样本时**选的（放行 63% / 误放 7%）；
# 63 条样本上实测是**放行 56% / 误放 21%**。**刻意没跟着改**：扫描表上那几个"更漂亮"的点
# 是样本内最优，5 折交叉验证下**没有一档同时赢过它**（见模块 docstring 那张表）。
VEC_FLOOR = 0.6134
BOTH_FLOOR = 0.6

# 重搜的换档顺序（方案 §2 P2：「策略池重搜一次——换策略：改写→HyDE→分解 或跨语言」）。
# 刻意是**固定顺序**而不是「挑最好的」：只重试一次，没有比较的余地；而且顺序本身可测。
RETRY_ORDER = ("rewrite", "hyde", "decompose")

# 重试预算，写死。方案 §2 P2 克制之一原话：「**只重试一次**。重试不是自由度，是预算
# ——CRAG 论文的核心也是单次纠偏，循环检索在个人库里只有成本没有收益」。
MAX_RETRIES = 1


@dataclass(frozen=True)
class Quality:
    """一次检索的质量判定。`reason` 给账本/日志看，不参与判断。"""

    ok: bool
    vec_top1: float
    both_frac: float
    reason: str


def vec_top1(hits: list[dict]) -> float:
    """这组命中里**向量路的原始相似度**最高值（= 向量通道自己的 top1）。Pure。

    每条的原始相似度挂在 `hit["vec"]`（`retriever._search_forms` 填的）。只有词法路命中
    的条没有这个值（`None`）——**跳过它们**，别把「缺失」当成 0 去拉低最高值。
    """
    vals = [h["vec"] for h in hits if isinstance(h.get("vec"), (int, float))]
    return float(max(vals)) if vals else 0.0


def both_frac(hits: list[dict]) -> float:
    """top-k 里「两个通道都命中」的占比。Pure。空结果记 0。"""
    if not hits:
        return 0.0
    return sum(1 for h in hits if len(h.get("channels") or []) >= 2) / len(hits)


def assess(
    hits: list[dict],
    *,
    vec_floor: float = VEC_FLOOR,
    both_floor: float = BOTH_FLOOR,
) -> Quality:
    """一组检索命中够不够好？Pure、确定性、零模型调用。

    两个判据**都要过**：向量路确实撞到了像的东西（`vec_top1`），而且不是单通道的侥幸
    （`both_frac`）。空结果直接不通过——没有材料就没什么可答的。
    """
    if not hits:
        return Quality(False, 0.0, 0.0, "没有检索到任何材料")

    v, b = vec_top1(hits), both_frac(hits)
    if v < vec_floor:
        return Quality(False, v, b, f"向量路最高相似度 {v:.4f} < {vec_floor}")
    if b < both_floor:
        return Quality(False, v, b, f"双通道占比 {b:.2f} < {both_floor}")
    return Quality(True, v, b, f"向量 {v:.4f} ≥ {vec_floor}、双通道占比 {b:.2f}")


def next_strategy(used: str) -> str | None:
    """重搜该换哪一档？用过了就取下一档；轮完返回 None（**不重试**）。Pure。

    只重试一次是方案的硬约束（§2 P2 克制之一：「重试不是自由度，是预算」），所以这里
    不给「循环到满意为止」的口子——`None` 就是「到此为止，拿现在这把材料去答」。

    注意这条路的**收益未证实**：P1c 实测三档策略（改写 / HyDE / 分解）在金标上都没超过
    单次检索，所以「换个说法再搜一遍」救不救得回来，要靠 P2 自己的消融量（门开/关对比）。
    """
    if used not in RETRY_ORDER:
        return RETRY_ORDER[0]
    i = RETRY_ORDER.index(used)
    return RETRY_ORDER[i + 1] if i + 1 < len(RETRY_ORDER) else None


def should_retry(
    quality: Quality, retries: int, max_retries: int = MAX_RETRIES
) -> bool:
    """还要不要再搜一次？Pure。

    两条都不成立才重搜：**门说不够好**，且**预算没花完**。这个判断刻意不放进编排图里
    ——方案 §2 P2 的验收写着「图节点不含任何判断逻辑」，所以图只负责把它接上，
    判断本身在这里，能被单测钉死。
    """
    return (not quality.ok) and retries < max_retries
